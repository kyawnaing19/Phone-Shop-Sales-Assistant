def get_policy(category: str) -> str:
    """
    Get policy text by category

    Args:
        category: warranty, return, payment, support, privacy, complaint, loyalty

    Returns:
        Policy text string
    """

    policies = {
        "warranty": WARRANTY_POLICY,
        "return": RETURN_POLICY,
        "payment": PAYMENT_METHODS,
        "support": CUSTOMER_SUPPORT,
        "privacy": PRIVACY_POLICY,
        "complaint": COMPLAINT_POLICY,
        "loyalty": LOYALTY_PROGRAM,
        "shop_info": str(SHOP_INFO),
    }

    return policies.get(category.lower(), "")


def detect_policy_category(message: str) -> str:
    """
    Detect which policy category the message is asking about

    Args:
        message: User message

    Returns:
        Policy category name
    """

    message_lower = message.lower()

    # Warranty
    if any(word in message_lower for word in ['warranty', 'အာမခံ', 'guarantee', 'repair', 'ပြင်ဆင်']):
        return "warranty"

    # Return/Exchange
    if any(word in message_lower for word in ['return', 'refund', 'exchange', 'ပြန်အမ်း', 'လဲလှယ်']):
        return "return"

    # Payment
    if any(word in message_lower for word in ['payment', 'pay', 'invoice', 'receipt', 'ငွေပေးချေ', 'ဘောင်ချာ']):
        return "payment"

    # Support/Contact
    if any(word in message_lower for word in ['support', 'contact', 'hour', 'location', 'ဆက်သွယ်', 'ကူညီ', 'အချိန်']):
        return "support"

    # Privacy
    if any(word in message_lower for word in ['privacy', 'data', 'security', 'protect', 'လုံခြုံ', 'အချက်အလက်']):
        return "privacy"

    # Complaint
    if any(word in message_lower for word in ['complaint', 'unhappy', 'problem', 'issue', 'ကန့်ကွက်', 'ပြဿနာ']):
        return "complaint"

    # Loyalty
    if any(word in message_lower for word in ['loyalty', 'member', 'point', 'vip', 'discount']):
        return "loyalty"

    # Default to support
    return "support"

